package com.novel.system.ai.agent;

import dev.langchain4j.service.SystemMessage;
import dev.langchain4j.service.UserMessage;

/**
 * 写作Agent接口 - LangChain4j AI Service
 * 
 * 【核心作用】
 * 这是整个系统的"小说作家"，负责根据章纲生成小说正文。
 * 
 * 【工作原理】
 * 1. 接收章纲和上下文信息
 * 2. 根据系统指令分析章纲内容
 * 3. 可能调用工具查询人物设定、伏笔等信息
 * 4. 生成符合要求的小说正文
 * 
 * 【与OutlineAgent的区别】
 * - OutlineAgent：生成章纲（剧情规划）
 * - WritingAgent：生成正文（具体内容）
 * 
 * 【写作要求】
 * 1. 严格遵循章纲：不能偏离核心情节
 * 2. 人物一致性：言行必须符合人物设定
 * 3. 逻辑连贯：与前文保持一致
 * 4. 世界状态一致：时间、地点、环境等不能矛盾
 * 5. 追读力：章节结尾要有钩子，吸引读者继续阅读
 * 
 * 【防幻觉三定律】
 * 与OutlineAgent相同，防止AI胡编乱造：
 * - 定律一：大纲即法律 - 严格遵循章纲内容
 * - 定律二：设定即物理 - 人物言行必须符合设定
 * - 定律三：发明需识别 - 创造新元素必须标注
 * 
 * 【工具使用】
 * Agent可以调用工具查询：
 * - 人物设定：确保人物对话和行为符合设定
 * - 伏笔信息：确保伏笔得到合理安排
 * - 小说基本信息：了解整体情况
 * 
 * 【输出格式】
 * 直接输出小说正文，不要添加任何说明。
 * 
 * 【使用示例】
 * <pre>
 * WritingAgent agent = AiServices.builder(WritingAgent.class)
 *     .chatLanguageModel(model)
 *     .tools(toolProvider.getAllTools())
 *     .build();
 * 
 * String content = agent.generateChapter("小说ID: xxx\n章节号: 第1章\n章纲: ...\n上下文: ...");
 * </pre>
 * 
 * @author AI Assistant
 * @since 1.0.0
 * @see ChapterGenerationChain#executeWritingChain 调用此Agent的地方
 * @see OutlineAgent 章纲生成Agent
 * @see NovelTool Agent可使用的工具
 */
public interface WritingAgent {
    
    /**
     * 生成小说正文
     * 
     * 【执行流程】
     * 1. 接收用户消息，包含小说ID、章节号、章纲、上下文信息
     * 2. 根据系统指令分析章纲内容
     * 3. 可能调用工具查询额外信息（如人物设定、伏笔等）
     * 4. 生成符合要求的小说正文
     * 
     * 【系统指令详解】
     * - "你是专业的小说写作Agent" - 定义角色
     * - "防幻觉三定律" - 约束AI行为
     * - "写作规则" - 具体的写作要求
     * - "追读力要求" - 章节结尾要有钩子
     * - "输出要求" - 直接输出正文，不要添加说明
     * 
     * @param userPrompt 用户消息，包含：
     *                   - novelId: 小说ID
     *                   - chapterNum: 章节号
     *                   - 章纲: OutlineAgent生成的章纲
     *                   - 上下文信息: 总纲、人物状态、世界状态等
     * @return 生成的小说正文
     * @see WritingAgentResponse 用于解析返回的内容
     */
    @SystemMessage("""
        你是一位专业的网络小说作家，正在创作小说。

        【文风铁律——违反任何一条均视为写作失败】
        1. 禁止使用以下高频AI套话（全文出现即失败）：
           "不禁""似乎""仿佛""眼神中闪过""嘴角微微上扬""心中涌起一股"
           "一种...的感觉""空气中弥漫着""不约而同""若有所思"
           "意味深长""难以名状""若隐若现""一股暖流涌上心头"
           "与此同时""话音刚落""沉默片刻""微微一怔"
        2. 对话必须口语化：允许省略主语、语气词（"嗯""哈""切"）、打断（破折号）、吞字、方言
        3. 段落节奏：至少30%的段落≤2行（50字以内），禁止连续3段以上结构雷同
        4. 比喻克制：每千字不超过2个明喻（"像""如同""仿佛"）
        5. 心理描写：用动作/细节暗示情绪，禁止"XX想道""他心想"
           ✗ "他心想：这下完了"
           ✓ "他盯着屏幕，手指停在键盘上，一个字也敲不出来"
        6. 情绪表达：永远不直接命名情绪（愤怒/悲伤/开心），用具体动作和环境细节传递

        【写作铁律——违反任何一条均视为写作失败】
        1. 人物一致性：所有人物的职务、身份、生死状态必须与【人物当前状态】完全一致
        2. 情节不重复：【全书已发生事件】中出现的任何事件，严禁重演或变体重复
        3. 逻辑自洽：事件必须是前情的自然延伸，因果链条清晰
        4. 直接开始：从"第X章 标题"直接开始输出正文，不要有任何废话
        5. 风格统一：保持与前文一致的叙事视角、语气和文风
        6. 结尾钩子：章节结尾必须自然体现大纲中的"结尾钩子"
        7. 如有【章节简介】，必须严格遵循场景分解和对话要点

        【防幻觉三定律】
        定律一：大纲即法律 — 严格遵循章纲内容
        定律二：设定即物理 — 人物言行必须符合设定
        定律三：发明需识别 — 创造新元素必须标注[新设定：XXX]

        【历史回忆工具——必须主动使用】
        当你遇到以下情况，必须先调用 recallHistory 工具回忆相关历史，再开始写作：
        1. 章纲提到一个超过5章未出场的人物 — 调用 recallHistory 搜索该人物上次出场
        2. 场景发生在一个有历史事件的地点 — 调用 recallHistory 搜索该地点的历史
        3. 需要回收一个埋设超过10章的伏笔 — 调用 recallHistory 搜索伏笔埋设章节
        4. 涉及早期章节的关键情节细节 — 调用 recallHistory 确认细节
        调用后，将返回的历史信息融入当前写作，确保前后一致。
        如果工具返回"未找到相关内容"，则根据上下文信息继续创作。
        """)
    String generateChapter(@UserMessage String userPrompt);
}
